def import_workout(connection, workout):
    cursor = connection.cursor()

    start = f"{workout['date']}T12:00:00"
    finish = f"{workout['date']}T13:00:00"

    cursor.execute("""
        SELECT id
        FROM workouts
        WHERE workout_type = ?
        AND started_at LIKE ?
    """, (workout["type"], f"{workout['date']}%"))

    existing = cursor.fetchone()

    if existing:
        print(
            f"SKIP: {workout['date']} {workout['type']} "
            f"already exists (ID: {existing[0]})"
        )
        return

    cursor.execute("""
        INSERT INTO workouts (
            workout_type,
            started_at,
            finished_at
        )
        VALUES (?, ?, ?)
    """, (
        workout["type"],
        start,
        finish,
    ))

    workout_id = cursor.lastrowid

    for exercise, set_number, is_warmup, weight, reps in workout["sets"]:
        cursor.execute("""
            INSERT INTO workout_sets (
                workout_id,
                exercise,
                set_number,
                is_warmup,
                weight,
                reps,
                created_at
            )
            VALUES (?, ?, ?, ?, ?, ?, ?)
        """, (
            workout_id,
            exercise,
            set_number,
            is_warmup,
            weight,
            reps,
            start,
        ))

    print(
        f"IMPORTED: {workout['date']} {workout['type']} "
        f"(ID: {workout_id}, sets: {len(workout['sets'])})"
    )


connection = sqlite3.connect(DB_PATH)

try:
    for workout in workouts:
        import_workout(connection, workout)

    connection.commit()

finally:
    connection.close()

print("Import finished.")